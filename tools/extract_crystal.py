#!/usr/bin/env python3
"""Extract the Crystal sprite engine's pixel templates and colour ramps
into a C header for the ESP32 port.

Reads www/js/crystal/engine.js (path given as argv[1]) and writes a header
(argv[2]). Only data is extracted - no code is executed from the source.
"""
import json
import re
import sys


def main():
    src_path, out_path = sys.argv[1], sys.argv[2]
    with open(src_path, "r", encoding="utf-8") as fh:
        src = fh.read()

    # FR is already valid JSON between the first '{' and the closing '};'
    m = re.search(r"const FR\s*=\s*(\{.*?\});\s*\n", src, re.S)
    fr = json.loads(m.group(1))

    def ramps(name):
        """Parse a JS table of  Name:['#aabbcc', ...]  entries."""
        m = re.search(r"const %s\s*=\s*\{(.*?)\};" % name, src, re.S)
        body = m.group(1)
        out = []
        for key, arr in re.findall(r"(\w+)\s*:\s*\[([^\]]*)\]", body):
            cols = re.findall(r"#([0-9a-fA-F]{6})", arr)
            out.append((key, cols))
        return out

    skin, hair, cloth = ramps("SKIN"), ramps("HAIR"), ramps("CLOTH")

    dirs = ["S", "SW", "W", "NW", "N"]
    h = len(fr["S"]["px"])
    w = len(fr["S"]["px"][0])

    # Report the material letters actually used, so the C side can map them.
    letters = set()
    for d in dirs:
        for row in fr[d]["rg"]:
            letters.update(row)
    shades = set()
    for d in dirs:
        for row in fr[d]["px"]:
            shades.update(row)

    lines = []
    A = lines.append
    A("/* Generated by tools/extract_crystal.py from the Crystal sprite")
    A(" * engine (www/js/crystal/engine.js in the feed repo). Do not edit by")
    A(" * hand - re-run the extractor instead.")
    A(" *")
    A(" * Each direction is a %dx%d template with two layers:" % (w, h))
    A(" *   rg[] names the material of each pixel (hair, top, skin, ...)")
    A(" *   px[] names the shade ramp index (#=outline, D/M/L=dark/mid/light)")
    A(" * The remaining three of the eight directions are horizontal mirrors.")
    A(" */")
    A("#pragma once")
    A("")
    A("#include <stdint.h>")
    A("")
    A("#define CRYS_W %d" % w)
    A("#define CRYS_H %d" % h)
    A("#define CRYS_DIRS %d" % len(dirs))
    A("")
    A("/* material letters in use: %s */" % "".join(sorted(letters)))
    A("/* shade letters in use:    %s */" % "".join(sorted(shades)))
    A("")

    for layer in ("rg", "px"):
        A("static const char *const CRYS_%s[CRYS_DIRS][CRYS_H] = {" % layer.upper())
        for d in dirs:
            A("    { /* %s */" % d)
            for row in fr[d][layer]:
                A('        "%s",' % row)
            A("    },")
        A("};")
        A("")

    for name, table in (("SKIN", skin), ("HAIR", hair), ("CLOTH", cloth)):
        width = max(len(c) for _, c in table)
        A("/* %s: %d ramps of up to %d shades */" % (name, len(table), width))
        A("#define CRYS_%s_COUNT %d" % (name, len(table)))
        A("#define CRYS_%s_SHADES %d" % (name, width))
        A("static const uint32_t CRYS_%s[CRYS_%s_COUNT][CRYS_%s_SHADES] = {"
          % (name, name, name))
        for key, cols in table:
            padded = cols + [cols[-1]] * (width - len(cols))
            A("    { %s }, /* %s */"
              % (", ".join("0x%s" % c.upper() for c in padded), key))
        A("};")
        A("")

    with open(out_path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print("template %dx%d, %d dirs" % (w, h, len(dirs)))
    print("materials: %s" % "".join(sorted(letters)))
    print("shades:    %s" % "".join(sorted(shades)))
    print("ramps: skin=%d hair=%d cloth=%d" % (len(skin), len(hair), len(cloth)))


main()
